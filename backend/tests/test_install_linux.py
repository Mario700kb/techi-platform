"""Phase 2 — Linux installer endpoint (flag-gated)."""


from fastapi import FastAPI
from fastapi.testclient import TestClient

from app.api.v1.endpoints import install as install_endpoint
from app.core.config import settings


def _client(monkeypatch, flag_on: bool) -> TestClient:
    monkeypatch.setattr(settings, "FEATURE_PLATFORM_CORE", flag_on)
    monkeypatch.setattr(settings, "FEATURE_LINUX", flag_on)
    app = FastAPI()
    app.include_router(install_endpoint.router, prefix="/api/v1/install")
    return TestClient(app)


def test_404_when_flag_off(monkeypatch):
    client = _client(monkeypatch, flag_on=False)
    resp = client.get("/api/v1/install/linux", params={"token": "TKN-1"})
    assert resp.status_code == 404


def test_script_served_when_flag_on(monkeypatch):
    client = _client(monkeypatch, flag_on=True)
    resp = client.get("/api/v1/install/linux", params={"token": "TKN-ABC"})
    assert resp.status_code == 200
    body = resp.text
    assert body.startswith("#!/usr/bin/env bash")
    assert "TOKEN=\"TKN-ABC\"" in body
    assert "linux-${ARCH}/download" in body
    assert "techi-agent" in body
    assert "install --config" in body


def test_token_required(monkeypatch):
    client = _client(monkeypatch, flag_on=True)
    resp = client.get("/api/v1/install/linux")
    assert resp.status_code == 422


# ── re-runnable installer (RISK-INSTALL-001) ─────────────────────────────── #
#
# The original script could only ever install onto a clean host. It wrote the
# download straight over /usr/local/bin/techi-agent, which the kernel refuses
# while that binary is running (ETXTBSY), so curl exited 23 and `set -euo
# pipefail` aborted — reproduced on device 729, 2026-08-05. Worse, had the
# download succeeded it would have overwritten the config that holds agent_id
# and device_id, forcing a re-enrolment on an already-known machine.


def _script(monkeypatch) -> str:
    return _client(monkeypatch, flag_on=True).get(
        "/api/v1/install/linux", params={"token": "TKN-ABC"}
    ).text


def test_generated_script_is_valid_bash(monkeypatch, tmp_path):
    """The script is generated by string interpolation; a stray brace would
    only ever be discovered on a customer's server."""
    import shutil
    import subprocess

    bash = shutil.which("bash")
    if bash is None:
        import pytest
        pytest.skip("bash not available")

    path = tmp_path / "install.sh"
    path.write_text(_script(monkeypatch))
    result = subprocess.run([bash, "-n", str(path)], capture_output=True, text=True)
    assert result.returncode == 0, result.stderr


def test_binary_is_not_downloaded_over_the_running_executable(monkeypatch):
    body = _script(monkeypatch)
    assert 'fetch "${BACKEND}' in body and '"${TMP_BIN}"' in body, (
        "download must land in a temp file"
    )
    assert '-o "${BIN_PATH}"' not in body, (
        "writing the download straight onto the running binary is what made "
        "this installer unusable on any host that already had the agent"
    )


def test_download_falls_back_to_wget(monkeypatch):
    """A minimal Debian ships neither curl nor wget; whichever fetched this
    script is not necessarily available for the binary download too (reported
    2026-08-05: "-bash: curl: command not found")."""
    body = _script(monkeypatch)
    assert "command -v curl" in body
    assert "wget -qO" in body
    assert "Neither curl nor wget is available" in body, (
        "with neither present the script must say so, not fail obscurely"
    )


def test_service_is_stopped_before_the_binary_is_replaced(monkeypatch):
    body = _script(monkeypatch)
    stop = body.index('systemctl stop "${SERVICE}"')
    install = body.index('install -m 0755')
    assert stop < install, "the binary cannot be replaced while it is running"


def test_download_happens_before_the_service_is_stopped(monkeypatch):
    """A failed download must cost no downtime."""
    body = _script(monkeypatch)
    assert body.index('fetch "${BACKEND}') < body.index('systemctl stop "${SERVICE}"')


def test_an_existing_configuration_is_never_overwritten(monkeypatch):
    """agent_id/device_id live in that file; rewriting it re-enrols a machine
    the platform already knows (RISK-IDENT-001)."""
    body = _script(monkeypatch)
    assert 'if [ -f "${CONFIG_PATH}" ]; then' in body
    assert "device identity preserved" in body
    config_guard = body.index('if [ -f "${CONFIG_PATH}" ]; then')
    config_write = body.index('cat > "${CONFIG_PATH}"')
    assert config_guard < config_write, "the write must sit in the else branch"


def test_enrollment_token_is_only_passed_when_not_yet_enrolled(monkeypatch):
    body = _script(monkeypatch)
    assert '"${BIN_PATH}" install --config "${CONFIG_PATH}"\n' in body, (
        "an enrolled host must be installed without a token, so the token is "
        "not baked into the systemd unit for no reason"
    )
    assert '--enrollment-token "${TOKEN}"' in body


def test_checksum_is_published_and_enforced(monkeypatch):
    body = _script(monkeypatch)
    assert "EXPECTED_SHA256=" in body
    assert "Checksum mismatch - refusing to install." in body
    assert "Checksum not verified" not in body, "an unverified binary is never installed"


def test_blockers_are_checked_before_anything_is_touched(monkeypatch):
    """No systemd (Alpine, Devuan, a container), no active package for the
    architecture (aarch64 got a 404 mid-run) or no sha256sum: the script stops
    before the download and before the running agent is stopped."""
    body = _script(monkeypatch)
    download = body.index('fetch "${BACKEND}')
    for check in (
        "if [ ! -d /run/systemd/system ] || ! command -v systemctl",
        'if [ -z "${EXPECTED_SHA256}" ]; then',
        "if ! command -v sha256sum",
    ):
        assert body.index(check) < download, check
    assert "No TECHI agent package is active for linux-${ARCH} - nothing was changed." in body


def test_previous_binary_is_backed_up(monkeypatch):
    body = _script(monkeypatch)
    assert 'BACKUP="${BIN_PATH}.bak-' in body
    assert "restoring previous binary" in body


# ── TECHI Remote Support on Linux desktops ──────────────────────────────── #


def _remote_support_section(body: str) -> str:
    return body[body.index("# --- TECHI Remote Support"):]


def test_remote_support_package_is_pinned_per_package_manager_and_architecture(monkeypatch):
    body = _script(monkeypatch)
    for (fmt, arch), (pkg, sha) in install_endpoint.RUSTDESK_LINUX_PACKAGES.items():
        assert f'{fmt}-{arch}) RS_PKG="{pkg}"; RS_SHA256="{sha}" ;;' in body
    assert "Remote Support checksum mismatch - not installing it." in body


def test_remote_support_reaches_rpm_and_arch_desktops_too(monkeypatch):
    """Ubuntu was not the only desktop: Fedora/RHEL, openSUSE and Arch got the
    agent but never Remote Support, because only apt-get could install it."""
    section = _remote_support_section(_script(monkeypatch))
    formats = {fmt for fmt, _ in install_endpoint.RUSTDESK_LINUX_PACKAGES}
    assert formats == {"deb", "rpm", "suse", "arch"}
    assert 'dnf install -y "$1"' in section
    assert 'zypper --non-interactive install --allow-unsigned-rpm "$1"' in section
    assert 'pacman -U --noconfirm "$1"' in section
    assert "rpm -q --qf '%{VERSION}' rustdesk" in section
    assert 'elif [ -z "${RS_PKG}" ]; then' in section


def test_remote_support_package_follows_the_userland_not_the_kernel(monkeypatch):
    """32-bit Raspberry Pi OS on a Pi 4/5 reports aarch64; dpkg refuses an
    arm64 package there."""
    section = _remote_support_section(_script(monkeypatch))
    assert 'case "$(dpkg --print-architecture 2>/dev/null)" in' in section
    assert 'case "${RS_FORMAT}-${RS_ARCH}" in' in section


def test_gnome_on_wayland_gets_the_x11_hint(monkeypatch):
    section = _remote_support_section(_script(monkeypatch))
    assert "WaylandEnable=false" in section
    assert "/etc/gdm3/custom.conf /etc/gdm/custom.conf" in section


def test_remote_support_points_at_the_platform_id_server(monkeypatch):
    section = _remote_support_section(_script(monkeypatch))
    assert f"custom-rendezvous-server = '{settings.RUSTDESK_SERVER_HOST}'" in section
    assert f"relay-server = '{settings.RUSTDESK_RELAY_HOST}'" in section
    assert f"key = '{settings.RUSTDESK_PUBLIC_KEY}'" in section
    assert "api-server = '${BACKEND}'" in section


def test_remote_support_options_also_go_through_the_rustdesk_cli(monkeypatch):
    """The file alone did not make the Pis register ("ID does not exist");
    `rustdesk --option` hands the options to the running service."""
    section = _remote_support_section(_script(monkeypatch))
    assert f"rs_option custom-rendezvous-server '{settings.RUSTDESK_SERVER_HOST}'" in section
    assert f"rs_option relay-server '{settings.RUSTDESK_RELAY_HOST}'" in section
    assert 'rs_option api-server "${BACKEND}"' in section
    assert f"rs_option key '{settings.RUSTDESK_PUBLIC_KEY}'" in section
    # --option goes to the running service: set after a start, then restarted.
    first_restart = section.index("systemctl restart rustdesk")
    assert first_restart < section.index("rs_option custom-rendezvous-server")
    assert section.index("rs_option key") < section.index("systemctl restart rustdesk", first_restart + 1)
    assert "rustdesk --option custom-rendezvous-server 2>/dev/null" in section


def test_one_run_is_enough_the_options_are_retried_until_they_hold(monkeypatch):
    """A fresh install lost an early --option, so the installer had to be run
    twice. It now waits for RustDesk, sets, restarts and reads back, at least
    twice and until the ID server is the platform's."""
    section = _remote_support_section(_script(monkeypatch))
    assert "for RS_PASS in 1 2 3 4 5; do" in section
    assert "rs_answers && break" in section
    assert '[ "${RS_PASS}" -ge 2 ]' in section
    loop = section[section.index("for RS_PASS"):section.index("done\n  if [ \"${RS_SERVER}\"")]
    assert loop.index("rs_option key") < loop.index("systemctl restart rustdesk")
    assert "rustdesk --get-id" in section


def test_remote_support_only_on_a_desktop_and_never_fails_the_install(monkeypatch):
    """A server without a desktop keeps the terminal only, and a Remote Support
    failure must not turn an installed agent into a failed run."""
    section = _remote_support_section(_script(monkeypatch))
    assert "elif ! has_desktop; then" in section
    assert 'if [ "$(uname -m)" = "armv6l" ]; then' in section
    assert "exit 1" not in section
    assert section.rstrip().endswith("exit 0")


def test_an_installed_remote_support_is_kept_whatever_its_version(monkeypatch):
    """A Pi with RustDesk 1.5.0 already on it: apt refuses the 1.4.6 downgrade,
    so the installer must keep it and only write the ID server options."""
    section = _remote_support_section(_script(monkeypatch))
    assert "dpkg-query -W -f='${Status} ${Version}' rustdesk" in section
    assert "already installed - keeping it." in section


def test_remote_support_is_installed_before_the_agent_starts(monkeypatch):
    """The first heartbeat must already carry Remote Support and its ID, so
    Connect on a new desktop never offers only the terminal."""
    body = _script(monkeypatch)
    assert body.index("elif ! install_remote_support; then") < body.index("Installing systemd service and enrolling...")
    assert body.rstrip().endswith("exit 0")


def test_script_needs_no_awk(monkeypatch):
    """A minimal openSUSE Tumbleweed has no awk: `sha256sum | awk` printed
    nothing there and every download looked like a checksum mismatch."""
    assert "awk" not in _script(monkeypatch)
